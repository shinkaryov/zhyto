export type UiText = typeof UI_TEXT.en

export const defaultLang: Lang = 'uk'

export const getStoredLang = (): Lang => {
  if (typeof window === 'undefined') {
    return defaultLang
  }
  const value = window.localStorage.getItem(LANG_STORAGE_KEY)
  return value === 'en' || value === 'uk' ? value : defaultLang
}

export const setStoredLang = (lang: Lang) => {
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(LANG_STORAGE_KEY, lang)
  }
}

